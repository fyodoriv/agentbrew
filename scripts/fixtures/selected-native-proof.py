def run(command, cwd, env):
    return subprocess.run(
        command, cwd=cwd, env=env, capture_output=True, timeout=30, check=False,
    )


def checked(command, cwd, env, failure):
    result = run(command, cwd, env)
    require(result.returncode == 0, failure)
    return result


def known_output(home, identity):
    plugin = identity["name"]
    data = home / ".local" / "share" / "agentbrew"
    market = data / "claude-marketplace"
    native = market / "plugins" / plugin
    source_manifest = {item["name"]: item for item in identity["files"]}
    envelope = {
        "name": plugin, "version": f"1.0.0+{identity['commit'][:8]}",
        "description": f"Company plugin {plugin}, managed by agentbrew",
    }
    hooks_file = native / "hooks" / "hooks.json"
    hooks = json.loads(hooks_file.read_text())["hooks"] if hooks_file.exists() else {}
    hook_script = native / "hooks" / "read-only.sh"
    hook_sha = source_manifest["hooks/read-only.sh"]
    hook_value = [{"matcher": "Bash", "hooks": [
        {"type": "command", "command": '${CLAUDE_PLUGIN_ROOT}/hooks/read-only.sh'},
    ]}]
    rule_hook = [{"hooks": [{
        "type": "command", "command": 'agentbrew plugin rules --agent claude-code --cwd "$CLAUDE_PROJECT_DIR"',
    }]}]
    launcher = data / "launchers" / f"{plugin}--fixture-native-server.sh"
    launcher_body = (
        "#!/bin/sh\n# Generated by agentbrew (#208). Resolves secret references at start.\n"
        "set -eu\nexec 'node' 'server.mjs'\n"
    )
    mcp = native / ".mcp.json"
    manifest_path = native / ".claude-plugin" / "plugin.json"
    index = market / ".claude-plugin" / "marketplace.json"
    paths = home / ".config" / "agentbrew"
    workspace = paths / "generated" / "workspace-Agentfile.yaml"
    pattern = home / ".local" / "state" / "agentbrew" / "redact-patterns.txt"
    settings = home / ".claude" / "settings.json"
    settings_data = json.loads(settings.read_text()) if settings.exists() else {}
    enabled = settings_data.get("enabledPlugins", {})
    enabled_key = f"{plugin}@agentbrew-plugins"
    marketplace_slot = settings_data.get("extraKnownMarketplaces", {}).get("agentbrew-plugins")
    return {
        "declared_hook": hooks.get("PreToolUse") == hook_value and hook_script.is_file() and
            digest(hook_script) == hook_sha["sha256"] and hook_script.stat().st_mode & 0o777 == hook_sha["mode"],
        "rule_hook": hooks.get("SessionStart") == rule_hook,
        "mcp_config": mcp.is_file() and json.loads(mcp.read_text()) == {
            "mcpServers": {"fixture-native-server": {"command": str(launcher), "args": []}},
        },
        "mcp_launcher": launcher.is_file() and launcher.read_text() == launcher_body and
            launcher.stat().st_mode & 0o777 == 0o755,
        "plugin_envelope": manifest_path.is_file() and json.loads(manifest_path.read_text()) == envelope,
        "marketplace_index": index.is_file() and json.loads(index.read_text()) == {
            "name": "agentbrew-plugins", "owner": {"name": "agentbrew"},
            "plugins": [{**envelope, "source": f"./plugins/{plugin}"}],
        },
        "enabled": enabled.get(enabled_key) is True and
            marketplace_slot == {"source": {"source": "directory", "path": str(market)}},
        "workspace": workspace.is_file() and
            workspace.read_text().split("\n", 1)[1] == "mcp:\n  - name: workspace-fixture\n    command: /bin/true\n",
        "redaction": pattern.is_file() and pattern.read_text() == "fixture-native-synthetic-redaction\n" and
            pattern.stat().st_mode & 0o777 == 0o600,
    }


def admitted_path(path):
    exact = {
        ".", "events.jsonl", "home", "home/.claude", "home/.claude/settings.json",
        "home/.config", "home/.config/agentbrew", "home/.config/agentbrew/last-seen.json",
        "home/.config/agentbrew/manifest.json", "home/.config/agentbrew/state.yaml",
        "home/.config/agentbrew/state.yaml.bak", "home/.config/agentbrew/sync-errors.json",
        "home/.config/agentbrew/generated", "home/.config/agentbrew/generated/workspace-Agentfile.yaml",
        "home/.config/agentbrew/metrics", "home/.config/agentbrew/metrics/latest.json",
        "home/.local", "home/.local/share", "home/.local/share/agentbrew",
        "home/.local/share/agentbrew/launchers",
        "home/.local/share/agentbrew/launchers/fixture-native--fixture-native-server.sh",
        "home/.local/state", "home/.local/state/agentbrew", "home/.local/state/agentbrew/redact-patterns.txt",
    }
    generated = (
        "home/.config/agentbrew/backups", "home/.config/agentbrew/rules",
        "home/.local/share/agentbrew/claude-marketplace", "home/.claude/codeassist/hooks-scripts",
    )
    exact.add("home/.claude/codeassist")
    context_snapshot = re.fullmatch(
        r"home/\.config/agentbrew/metrics/context-budget-\d{4}-\d{2}-\d{2}\.json", path,
    )
    return path in exact or bool(context_snapshot) or any(
        path == prefix or path.startswith(prefix + "/") for prefix in generated
    )


def public_record(entry, root, relative_path):
    if entry is None:
        return None
    mode, mtime, content = entry
    if (mode & 0o170000) == 0o120000:
        target = Path(content)
        absolute = (root / relative_path.parent / target).resolve()
        require(absolute.is_relative_to(root), "Native fixture produced an outside link")
        content = str(absolute.relative_to(root)) if target.is_absolute() else content
    return {"mode": mode, "mtime_ns": mtime, "digest_or_link": content}


def package_mutation(before, after):
    altered = [p for p in before.keys() & after.keys() if before[p] != after[p]]
    return {
        "removed": sorted(str(p) for p in before.keys() - after.keys()),
        "added_count": len(after.keys() - before.keys()),
        "altered": {
            str(p): {
                "mode": before[p][0] != after[p][0], "mtime": before[p][1] != after[p][1],
                "data": before[p][2] != after[p][2],
            }
            for p in sorted(altered, key=str)
        },
    }


def setup_case(root, fixture, repo, node, loader):
    outside_observer = root / (fixture.name + "-observer")
    outside_observer.mkdir()
    work, env = fixture_env(fixture, outside_observer)
    home = Path(env["HOME"])
    config = home / ".config" / "agentbrew"
    state = {
        "schemaVersion": 1,
        "agents": [{"name": "claude-code", "detected": False, "configDir": str(home / ".claude")}],
        "catalogVersion": "0.1.0",
    }
    (config / "state.yaml").write_text(json.dumps(state))
    now = datetime.datetime.now(datetime.timezone.utc).isoformat()
    (config / "upgrade-check.json").write_text(json.dumps({"checkedAt": now, "latestVersion": "1.0.0"}))
    sample = work / "synthetic-project"
    sample.mkdir()
    (sample / "Agentfile.yaml").write_text("mcp:\n  - name: workspace-fixture\n    command: /bin/true\n")
    source = fixture / "plugin-source"
    source.mkdir()
    os.chmod(source, 0o700)
    env.update({
        "GIT_CONFIG_GLOBAL": "/dev/null", "GIT_CONFIG_SYSTEM": "/dev/null", "GIT_CONFIG_NOSYSTEM": "1",
        "GIT_ALLOW_PROTOCOL": "file", "GIT_TERMINAL_PROMPT": "0", "GIT_OPTIONAL_LOCKS": "0",
        "TSX_DISABLE_CACHE": "1", "AGENTBREW_POSTHOG_KEY": "",
    })
    checked(["/usr/bin/git", "init", "-q"], work, env, "Fixture workspace setup failed")
    checked(["/usr/bin/git", "remote", "add", "origin", "https://fixture.example/workspace.git"],
            work, env, "Fixture workspace origin setup failed")
    checked(["/usr/bin/git", "add", "--all"], work, env, "Fixture workspace staging failed")
    checked(["/usr/bin/git", "-c", "user.name=Fixture", "-c", "user.email=fixture@example.com",
             "commit", "-qm", "Synthetic workspace"],
            work, env, "Fixture workspace commit failed")
    key = outside_observer / "scratch-signer"
    checked(["/usr/bin/ssh-keygen", "-q", "-t", "ed25519", "-N", "", "-f", str(key)],
            work, env, "Fixture signer setup failed")
    receipt = outside_observer / "fixture.json"
    script = repo / "scripts" / "fixtures" / "selected-native-setup.mts"
    checked([node, "--import", str(loader), str(script), str(source), str(key), str(receipt)],
            work, env, "Signed fixture installation did not qualify")
    key.unlink()
    key.with_suffix(".pub").unlink()
    identity = json.loads(receipt.read_text())
    data = home / ".local" / "share" / "agentbrew"
    checkout = data / "plugins" / identity["name"]
    marketplace = data / "claude-marketplace"
    (marketplace / "fixture-marker.txt").unlink()
    marketplace.rmdir()
    require(all(identity[field] for field in ("tagObject", "commit", "tree", "fingerprint", "capabilitiesHash")),
            "The signed fixture identity recording is incomplete")
    env["NATIVE_FIXTURE_PROCESS_RECEIPT"] = str(outside_observer / "processes")
    env["NATIVE_FIXTURE_GIT_ROOTS"] = json.dumps({
        "plugin": str(checkout.resolve()), "workspace": str(work.resolve()), "sample": str(sample.resolve()),
    })
    return work, home, env, identity, checkout, source, outside_observer


def main():
    node, repo_path, outside_net, runner_uid, revision, candidate, scratch = sys.argv[1:]
    require(os.getuid() == int(runner_uid) and os.getuid() != 0, "Wrong native fixture user")
    require(os.readlink("/proc/self/ns/net") != outside_net, "Native fixture network namespace was not isolated")
    interfaces = {line.split(":", 1)[0].strip() for line in Path("/proc/net/dev").read_text().splitlines()[2:]}
    require(interfaces == {"lo"}, "Unexpected native fixture network interface")
    repo = Path(repo_path)
    bundle = repo / "dist" / "cli.js"
    loader = repo / "node_modules" / "tsx" / "dist" / "loader.mjs"
    preload = repo / "scripts" / "fixtures" / "selected-native-preload.mjs"
    require(json.loads((bundle.parent / "build-info.json").read_text())["commit"] == revision,
            "Wrong native fixture build revision")
    bundle_digest = digest(bundle)
    print(f"Native fixture candidate {candidate} bundle sha256 {bundle_digest}", flush=True)
    evidence = Path(scratch) / "public-native-observations.ndjson"
    with tempfile.TemporaryDirectory(dir=scratch) as tmp:
        root = Path(tmp)
        archives = list(Path(scratch).glob("agentbrew-*.tgz"))
        require(len(archives) == 1, "The native fixture requires one published-layout npm pack")
        extract = root / "distribution"
        extract.mkdir()
        with tarfile.open(archives[0], "r:gz") as archive:
            archive.extractall(extract, filter="data")
        install = extract / "package"
        installed_bundle = install / "dist" / "cli.js"
        require(digest(installed_bundle) == bundle_digest, "The scratch CLI bundle differs from the build")
        require((install / "hooks" / "manifest.yaml").is_file() and
                (install / "templates" / "rules").is_dir() and not (install / ".git").exists(),
                "The scratch CLI package layout is incomplete")
        packaged_hooks = [
            str(path) for path in (install / "hooks").rglob("*.sh")
            if path.is_file() and path.resolve() == path
        ]
        require(packaged_hooks, "The npm package contained no regular hook sources")
        install_before = manifest(install)
        all_complete = True
        cases = {
            facet: setup_case(root, root / facet, repo, node, loader)
            for facet in ("hooks", "mcp", "rules", "default")
        }
        case_paths = {facet: (root / facet, case[-1]) for facet, case in cases.items()}
        snapshots = {
            facet: tuple(manifest(path) for path in paths)
            for facet, paths in case_paths.items()
        }
        for facet, (_work, _home, _env, identity, _checkout, _source, _observer) in cases.items():
            print(json.dumps({"facet": facet, "signed_fixture": identity}, sort_keys=True), flush=True)
        for facet, (work, home, env, identity, checkout, source, observer) in cases.items():
            fixture = root / facet
            env["NATIVE_FIXTURE_BASH_FILES"] = json.dumps(packaged_hooks)
            if facet == "hooks":
                canary = observer / "canary"
                canary_env = {**env, "NATIVE_FIXTURE_PROCESS_RECEIPT": str(canary)}
                denied = run([
                    node, "--import", str(preload), "--input-type=module", "-e",
                    """import { spawnSync, execFileSync } from 'node:child_process';
for (const attempt of [
  () => spawnSync('/bin/true'),
  () => execFileSync('git', ['rev-parse', 'HEAD'], {cwd:process.env.TMPDIR}),
  () => execFileSync('git', ['--version']),
]) {
  try { attempt(); process.exit(9); } catch {}
}""",
                ], work, canary_env)
                require(denied.returncode == 0 and canary.read_text().splitlines() == ["preload", *(["denied"] * 3)],
                        "The native fixture denied-process control did not qualify")
                print("Native fixture canaries: three denied attempts", flush=True)
            identity_before = manifest(checkout)
            source_before = manifest(source)
            work_before = manifest(work)
            before = manifest(fixture)
            args = [
                node, "--import", str(preload), str(installed_bundle), "sync",
                "--no-recommended", "--workspaces", str(work),
            ]
            if facet != "default":
                args += ["--only", facet]
            result = run(args, work, env)
            package_after = manifest(install)
            if package_after != install_before:
                print(json.dumps({
                    "facet": facet, "exit": result.returncode, "complete": False,
                    "package_mutation": package_mutation(install_before, package_after),
                }, sort_keys=True), flush=True)
                raise SystemExit("A native sync arm changed the shared npm package")
            after = manifest(fixture)
            require(
                all(tuple(manifest(path) for path in paths) == snapshots[sibling]
                    for sibling, paths in case_paths.items() if sibling != facet),
                "A native sync arm changed a sibling fixture",
            )
            snapshots[facet] = (after, manifest(observer))
            changed = sorted((k for k in before.keys() | after.keys() if before.get(k) != after.get(k)), key=str)
            known = [k for k in changed if admitted_path(str(k))]
            require(len(known) <= 1_024, "Native fixture report exceeds the entry bound")
            delta = {
                str(key): [public_record(before.get(key), fixture, key), public_record(after.get(key), fixture, key)]
                for key in known
            }
            protected = [
                Path("home/.config/agentbrew/agentbrew.lock"),
                Path("home/.config/agent-plugins/allowed_signers"),
            ]
            lock_and_signer_unchanged = all(before.get(key) is not None and before.get(key) == after.get(key)
                                            for key in protected)
            processes = (observer / "processes").read_text().splitlines()
            outputs = known_output(home, identity)
            required = {
                "hooks": ("declared_hook",),
                "mcp": ("mcp_config", "mcp_launcher"),
                "rules": ("rule_hook",),
                "default": tuple(outputs),
            }[facet]
            complete = (
                result.returncode == 0 and processes.count("preload") == 1 and
                {"plugin-head", "plugin-tree", "plugin-clean"}.issubset(processes) and
                "local-git-error" not in processes and "packaged-bash-error" not in processes and
                "denied" not in processes and
                identity_before == manifest(checkout) and source_before == manifest(source) and
                work_before == manifest(work) and all(outputs[field] for field in required) and
                len(known) == len(changed) and lock_and_signer_unchanged
            )
            all_complete = all_complete and complete
            summary = {
                "facet": facet, "exit": result.returncode, "complete": complete, "outputs": outputs,
                "changed_entries": len(changed), "unclassified_entries": len(changed) - len(known),
                "git_reads": processes.count("local-git-success"), "git_errors": processes.count("local-git-error"),
                "bash_syntax_checks": processes.count("packaged-bash-parse"),
                "denied": processes.count("denied"), "lock_and_signer_unchanged": lock_and_signer_unchanged,
            }
            record = json.dumps({**summary, "signed_fixture": identity, "changes": delta}, sort_keys=True)
            require(len(record.encode()) <= 1024 * 1024, "Native fixture report exceeds the byte bound")
            with evidence.open("a", encoding="utf-8") as output:
                output.write(record + "\n")
            print(json.dumps(summary, sort_keys=True), flush=True)
        require(all_complete, "The selected native baseline contains incomplete cases")
    require(digest(bundle) == bundle_digest, "The selected native baseline changed its bundle")


if __name__ == "__main__":
    main()
