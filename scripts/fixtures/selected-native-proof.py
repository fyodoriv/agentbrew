def run(command, cwd, env):
    return subprocess.run(
        command, cwd=cwd, env=env, capture_output=True, timeout=30, check=False,
    )


def checked(command, cwd, env, failure):
    result = run(command, cwd, env)
    require(result.returncode == 0, failure)
    return result


def known_output(home, identity):
    plugin = identity["name"]
    data = home / ".local" / "share" / "agentbrew"
    market = data / "claude-marketplace"
    native = market / "plugins" / plugin
    source_manifest = {item["name"]: item for item in identity["files"]}
    envelope = {
        "name": plugin, "version": f"1.0.0+{identity['commit'][:8]}",
        "description": f"Company plugin {plugin}, managed by agentbrew",
    }
    hooks_file = native / "hooks" / "hooks.json"
    hooks = json.loads(hooks_file.read_text())["hooks"] if hooks_file.exists() else {}
    hook_script = native / "hooks" / "read-only.sh"
    hook_sha = source_manifest["hooks/read-only.sh"]
    hook_value = [{"matcher": "Bash", "hooks": [
        {"type": "command", "command": '${CLAUDE_PLUGIN_ROOT}/hooks/read-only.sh'},
    ]}]
    rule_hook = [{"hooks": [{
        "type": "command", "command": 'agentbrew plugin rules --agent claude-code --cwd "$CLAUDE_PROJECT_DIR"',
    }]}]
    launcher = data / "launchers" / f"{plugin}--fixture-native-server.sh"
    launcher_body = (
        "#!/bin/sh\n# Generated by agentbrew (#208). Resolves secret references at start.\n"
        "set -eu\nexec 'node' 'server.mjs'\n"
    )
    mcp = native / ".mcp.json"
    manifest_path = native / ".claude-plugin" / "plugin.json"
    index = market / ".claude-plugin" / "marketplace.json"
    paths = home / ".config" / "agentbrew"
    workspace = paths / "generated" / "workspace-Agentfile.yaml"
    pattern = home / ".local" / "state" / "agentbrew" / "redact-patterns.txt"
    settings = home / ".claude" / "settings.json"
    settings_data = json.loads(settings.read_text()) if settings.exists() else {}
    enabled = settings_data.get("enabledPlugins", {})
    enabled_key = f"{plugin}@agentbrew-plugins"
    marketplace_slot = settings_data.get("extraKnownMarketplaces", {}).get("agentbrew-plugins")
    return {
        "declared_hook": hooks.get("PreToolUse") == hook_value and hook_script.is_file() and
            digest(hook_script) == hook_sha["sha256"] and hook_script.stat().st_mode & 0o777 == hook_sha["mode"],
        "rule_hook": hooks.get("SessionStart") == rule_hook,
        "mcp_config": mcp.is_file() and json.loads(mcp.read_text()) == {
            "mcpServers": {"fixture-native-server": {"command": str(launcher), "args": []}},
        },
        "mcp_launcher": launcher.is_file() and launcher.read_text() == launcher_body and
            launcher.stat().st_mode & 0o777 == 0o755,
        "plugin_envelope": manifest_path.is_file() and json.loads(manifest_path.read_text()) == envelope,
        "marketplace_index": index.is_file() and json.loads(index.read_text()) == {
            "name": "agentbrew-plugins", "owner": {"name": "agentbrew"},
            "plugins": [{**envelope, "source": f"./plugins/{plugin}"}],
        },
        "enabled": enabled.get(enabled_key) is True and
            marketplace_slot == {"source": {"source": "directory", "path": str(market)}},
        "workspace": workspace.is_file() and
            workspace.read_text().split("\n", 1)[1] == "mcp:\n  - name: workspace-fixture\n    command: /bin/true\n",
        "redaction": pattern.is_file() and pattern.read_text() == "fixture-native-synthetic-redaction\n" and
            pattern.stat().st_mode & 0o777 == 0o600,
    }


