def public_record(entry, root, relative_path):
    if entry is None:
        return None
    mode, mtime, content = entry
    if (mode & 0o170000) == 0o120000:
        target = Path(content)
        absolute = (root / relative_path.parent / target).resolve()
        require(absolute.is_relative_to(root), "Native fixture produced an outside link")
        content = str(absolute.relative_to(root)) if target.is_absolute() else content
    return {"mode": mode, "mtime_ns": mtime, "digest_or_link": content}


def package_mutation(before, after):
    altered = [p for p in before.keys() & after.keys() if before[p] != after[p]]
    return {
        "removed": sorted(str(p) for p in before.keys() - after.keys()),
        "added_count": len(after.keys() - before.keys()),
        "altered": {
            str(p): {
                "mode": before[p][0] != after[p][0], "mtime": before[p][1] != after[p][1],
                "data": before[p][2] != after[p][2],
            }
            for p in sorted(altered, key=str)
        },
    }


def default_package_context(install, before, after):
    context = Path("dist/context")
    headings = {
        context / "chatgpt.md": (
            "# Custom Instructions for ChatGPT\n\n"
            "> Auto-generated from AGENTS.md template. Do not edit directly.\n"
            "> Paste this into ChatGPT → Settings → Personalization → Custom Instructions\n\n"
        ),
        context / "claude-desktop.md": (
            "# Project Instructions for Claude\n\n"
            "> Auto-generated from AGENTS.md template. Do not edit directly.\n"
            "> Paste this into a Claude Project → Project Instructions\n\n"
        ),
    }
    new_paths = {context, *headings}
    if after.keys() - before.keys() != new_paths or before.keys() - after.keys():
        return False
    folder = Path("dist")
    if any(value != after[key] for key, value in before.items() if key != folder):
        return False
    original_mode, _, original_data = before[folder]
    current_mode, _, current_data = after[folder]
    if (original_mode, original_data) != (current_mode, current_data):
        return False
    if after[context][0] != 0o40755:
        return False
    template = (install / "dist" / "templates" / "AGENTS.md").read_text()
    return all(after[path][0] == 0o100644 and (install / path).read_text() == heading + template
               for path, heading in headings.items())


def default_fallback_outputs(home, install, tmp, tmp_before):
    commands = home / ".claude" / "commands"
    shipped = install / "dist" / "commands"
    names = {"agentbrew.md", "offline.md", "verify.md"}
    directories = [home / ".claude" / "skills", home / ".agents" / "skills"]
    tmp_after = tmp.stat()
    return (
        commands.is_dir() and not commands.is_symlink() and
        {entry.name for entry in commands.iterdir()} == names and
        all((commands / name).is_file() and not (commands / name).is_symlink() and
            digest(commands / name) == digest(shipped / name) for name in names) and
        all(directory.is_dir() and not directory.is_symlink() and not any(directory.iterdir())
            for directory in directories) and
        (tmp_after.st_dev, tmp_after.st_ino, tmp_after.st_mode) ==
        (tmp_before.st_dev, tmp_before.st_ino, tmp_before.st_mode) and not any(tmp.iterdir())
    )


def setup_case(root, fixture, repo, node, loader):
    outside_observer = root / (fixture.name + "-observer")
    outside_observer.mkdir()
    work, env = fixture_env(fixture, outside_observer)
    home = Path(env["HOME"])
    config = home / ".config" / "agentbrew"
    state = {
        "schemaVersion": 1,
        "agents": [{"name": "claude-code", "detected": False, "configDir": str(home / ".claude")}],
        "catalogVersion": "0.1.0",
    }
    (config / "state.yaml").write_text(json.dumps(state))
    now = datetime.datetime.now(datetime.timezone.utc).isoformat()
    (config / "upgrade-check.json").write_text(json.dumps({"checkedAt": now, "latestVersion": "1.0.0"}))
    sample = work / "synthetic-project"
    sample.mkdir()
    (sample / "Agentfile.yaml").write_text("mcp:\n  - name: workspace-fixture\n    command: /bin/true\n")
    source = fixture / "plugin-source"
    source.mkdir()
    os.chmod(source, 0o700)
    env.update({
        "GIT_CONFIG_GLOBAL": "/dev/null", "GIT_CONFIG_SYSTEM": "/dev/null", "GIT_CONFIG_NOSYSTEM": "1",
        "GIT_ALLOW_PROTOCOL": "file", "GIT_TERMINAL_PROMPT": "0", "GIT_OPTIONAL_LOCKS": "0",
        "TSX_DISABLE_CACHE": "1", "AGENTBREW_POSTHOG_KEY": "",
    })
    checked(["/usr/bin/git", "init", "-q"], work, env, "Fixture workspace setup failed")
    checked(["/usr/bin/git", "remote", "add", "origin", "https://fixture.example/workspace.git"],
            work, env, "Fixture workspace origin setup failed")
    checked(["/usr/bin/git", "add", "--all"], work, env, "Fixture workspace staging failed")
    checked(["/usr/bin/git", "-c", "user.name=Fixture", "-c", "user.email=fixture@example.com",
             "commit", "-qm", "Synthetic workspace"],
            work, env, "Fixture workspace commit failed")
    key = outside_observer / "scratch-signer"
    checked(["/usr/bin/ssh-keygen", "-q", "-t", "ed25519", "-N", "", "-f", str(key)],
            work, env, "Fixture signer setup failed")
    receipt = outside_observer / "fixture.json"
    script = repo / "scripts" / "fixtures" / "selected-native-setup.mts"
    checked([node, "--import", str(loader), str(script), str(source), str(key), str(receipt)],
            work, env, "Signed fixture installation did not qualify")
