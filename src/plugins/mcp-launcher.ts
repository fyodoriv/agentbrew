/**
 * Secrets by reference and launcher rendering (issue #208, step 9).
 *
 * A plugin MCP server names each env value as a reference:
 * `env:<NAME>`, `keychain:<item>`, or `op://...`. Literal values are refused.
 * agentbrew renders one POSIX launcher per server that resolves the
 * references at process start and `exec`s the server. Agent configs only
 * name the launcher, so no secret value is ever written to them.
 * npx/bunx/uvx/pipx packages must be pinned to an exact version.
 */
import { chmodSync, existsSync, mkdirSync, readFileSync } from "node:fs";
import { homedir } from "node:os";
import { join } from "node:path";
import yaml from "js-yaml";
import { sync as writeFileSync } from "write-file-atomic";
import type { PluginManifest } from "./manifest.js";

export interface PluginMcpServer {
  name: string;
  command: string;
  args?: string[];
  env?: Record<string, string>;
}

const REFERENCE = /^(env:[A-Za-z_][A-Za-z0-9_]*|keychain:[^\s'"]+|op:\/\/\S+)$/;
const NODE_RUNNERS = new Set(["npx", "bunx", "pnpx"]);
const PY_RUNNERS = new Set(["uvx", "pipx"]);
const EXACT_NODE = /^(@[^/@\s]+\/)?[^@\s]+@\d+\.\d+\.\d+([-+][0-9A-Za-z.-]+)?$/;
const EXACT_PY = /^[A-Za-z0-9_.-]+(==|@)\d+(\.\d+)*([-+.][0-9A-Za-z.-]+)?$/;

function pinViolation(server: PluginMcpServer): string | undefined {
  const runner = server.command.split("/").pop() ?? server.command;
  if (!NODE_RUNNERS.has(runner) && !PY_RUNNERS.has(runner)) return undefined;
  const args = server.args ?? [];
  const pkg = args.find((a, i) => !a.startsWith("-") && !(runner === "pipx" && i === 0 && a === "run"));
  if (!pkg) return `${server.name}: ${runner} has no package`;
  const exact = NODE_RUNNERS.has(runner) ? EXACT_NODE : EXACT_PY;
  return exact.test(pkg) ? undefined : `${server.name}: ${runner} package ${pkg} is not pinned to an exact version`;
}

/** Every reason the entries are unsafe. Empty means valid. */
export function validateMcpServers(servers: PluginMcpServer[]): string[] {
  const errors: string[] = [];
  for (const server of servers) {
    for (const [key, value] of Object.entries(server.env ?? {})) {
      if (!REFERENCE.test(String(value))) {
        errors.push(`${server.name}: env ${key} must be a reference (keychain:, env:, op://), not a literal value`);
      }
    }
    const pin = pinViolation(server);
    if (pin) errors.push(pin);
  }
  return errors;
}

/** Read the plugin's `contributes.mcp_servers` file (list form or name-keyed map). */
export function readPluginMcpServers(dir: string, manifest: PluginManifest): PluginMcpServer[] {
  const rel = manifest.contributes?.mcp_servers;
  if (typeof rel !== "string" || !existsSync(join(dir, rel))) return [];
  const parsed = yaml.load(readFileSync(join(dir, rel), "utf-8"));
  if (Array.isArray(parsed)) return parsed as PluginMcpServer[];
  if (parsed && typeof parsed === "object") {
    return Object.entries(parsed as Record<string, Omit<PluginMcpServer, "name">>).map(([name, s]) => ({ ...s, name }));
  }
  return [];
}

/** Throw when any entry is unsafe. */
export function assertMcpServers(dir: string, manifest: PluginManifest): void {
  const errors = validateMcpServers(readPluginMcpServers(dir, manifest));
  if (errors.length > 0) throw new Error(`Unsafe MCP servers in plugin ${manifest.name}:\n  ${errors.join("\n  ")}`);
}

export function launcherPath(plugin: string, server: string): string {
  return join(homedir(), ".local", "share", "agentbrew", "launchers", `${plugin}--${server}.sh`);
}

function shQuote(value: string): string {
  return `'${value.replace(/'/g, `'\\''`)}'`;
}

function resolveLine(key: string, ref: string): string {
  if (ref.startsWith("env:")) {
    const name = ref.slice(4);
    return `export ${key}="\${${name}:?env ${name} is not set (needed by this MCP server)}"`;
  }
  if (ref.startsWith("keychain:")) {
    const item = shQuote(ref.slice(9));
    return [
      `if command -v security >/dev/null 2>&1; then ${key}="$(security find-generic-password -s ${item} -w)"`,
      `else ${key}="$(secret-tool lookup service ${item})"; fi`,
      `export ${key}`,
    ].join("\n");
  }
  return `export ${key}="$(op read ${shQuote(ref)})"`;
}

/** Write the launcher for one server; return its path. */
export function renderLauncher(plugin: string, server: PluginMcpServer): string {
  if (!/^[A-Za-z0-9_.-]+$/.test(server.name)) throw new Error(`Bad MCP server name: ${server.name}`);
  const lines = ["#!/bin/sh", "# Generated by agentbrew (#208). Resolves secret references at start.", "set -eu"];
  for (const [key, ref] of Object.entries(server.env ?? {})) {
    if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(key)) throw new Error(`Bad env name: ${key}`);
    lines.push(resolveLine(key, ref));
  }
  lines.push(`exec ${[server.command, ...(server.args ?? [])].map(shQuote).join(" ")}`);
  const path = launcherPath(plugin, server.name);
  mkdirSync(join(path, ".."), { recursive: true });
  writeFileSync(path, `${lines.join("\n")}\n`);
  chmodSync(path, 0o755);
  return path;
}
